CREATE TABLE IF NOT EXISTS districts (
  id UUID PRIMARY KEY,
  province_id UUID NOT NULL REFERENCES provinces(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  name_si TEXT NULL,
  name_ta TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(province_id, name)
);

